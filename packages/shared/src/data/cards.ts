export const ENCHANTMENT_DEFINITIONS_BY_ID: Record<string, EnchantmentCardDefinition> = Object.fromEntries(
  ENCHANTMENT_DEFINITIONS.map((c) => [c.id, c])
);

/** Every card eligible to appear in the deck at all — implemented ones, before any per-room disabling. Used to populate the Options screen's card list. */
export function eligibleDeckDefinitions(): EnchantmentCardDefinition[] {
  return ENCHANTMENT_DEFINITIONS.filter((c) => c.implementationStatus === "implemented");
}

/** The actual deck for a room: eligible cards minus whichever the host disabled on the Options screen. */
export function playableDeckDefinitions(disabledCardIds?: Iterable<string>): EnchantmentCardDefinition[] {
  const disabled = new Set(disabledCardIds ?? []);
  return eligibleDeckDefinitions().filter((c) => !disabled.has(c.id));
}
